              local ok, devicons = pcall(require, "nvim-web-devicons")
              if ok then
                local name = node.type == "terminal" and "terminal" or node.name
                local devicon, hl = devicons.get_icon(name)
                if devicon then
                  icon.text = devicon
                end
                if hl then
                  icon.highlight = hl
                end
              end
